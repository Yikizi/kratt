class TestSetKind(str, Enum):
    POSITIVE = "positive"            # Should fire — measure recall
    NEGATIVE_GENERAL = "negative"    # General speech, should not fire — measure FPR / FAPH
    NEGATIVE_HARD = "hard_negative"  # Phonetically similar phrases — measure FPR
    AMBIENT = "ambient"              # Long-form ambient — measure FAPH


@dataclass(frozen=True)
class TestSet:
    name: str
    path: Path
    kind: TestSetKind
    description: str
    held_out_for: tuple[str, ...]  # Tuple of model versions for which this is truly held out
    notes: str = ""

    def file_count(self) -> int:
        if not self.path.exists():
            return 0
        return len(list(self.path.rglob("*.wav")))

    def is_held_out_for(self, model_version: str) -> bool:
        return model_version in self.held_out_for or "all" in self.held_out_for


