def get_test_set(name: str) -> TestSet:
    if name not in TEST_SETS:
        raise KeyError(f"Unknown test set: {name}. Available: {sorted(TEST_SETS)}")
    return TEST_SETS[name]


def list_test_sets(
    *, kind: TestSetKind | None = None, held_out_for: str | None = None
) -> list[TestSet]:
    sets = list(TEST_SETS.values())
    if kind is not None:
        sets = [s for s in sets if s.kind == kind]
    if held_out_for is not None:
        sets = [s for s in sets if s.is_held_out_for(held_out_for)]
    return sets


def assert_disjoint_from_training(test_set: TestSet, model_version: str) -> None:
    """Walk the test set and verify it shares no files (by resolved real path)
    with any training source for the given model version.

    Raises AssertionError if a leak is detected.
    Useful as a tripwire when adding new test sets.
    """
    if model_version not in TRAINING_SOURCES:
        # No inventory recorded for this model — fall back to declared metadata
        if not test_set.is_held_out_for(model_version):
            raise AssertionError(
                f"Test set {test_set.name!r} is not declared as held-out for "
                f"{model_version!r} and no training inventory is recorded."
            )
        return

    if not test_set.path.exists():
        return  # Empty set is trivially disjoint

    test_files = {p.resolve() for p in test_set.path.rglob("*.wav")}

    leaked: list[Path] = []
    for kind, dirs in TRAINING_SOURCES[model_version].items():
        for d in dirs:
            if not d.exists():
                continue
            for src in d.rglob("*.wav"):
                if src.resolve() in test_files:
                    leaked.append(src)

    if leaked:
        raise AssertionError(
            f"DATA LEAKAGE: {len(leaked)} files from test set {test_set.name!r} "
            f"appear in {model_version!r} training data. Examples: "
            f"{[str(p) for p in leaked[:3]]}"
        )


def summary() -> str:
    lines = ["Registered test sets:"]
    for ts in TEST_SETS.values():
        n = ts.file_count()
        held = ", ".join(ts.held_out_for) if ts.held_out_for != ALL_MODELS else "all"
        lines.append(
            f"  {ts.name:24s} kind={ts.kind.value:14s} files={n:5d}  held-out for: {held}"
        )
    return "\n".join(lines)


if __name__ == "__main__":
    print(summary())
    print()
    print("Verifying disjointness for v8 ...")
    for ts in TEST_SETS.values():
        try:
            assert_disjoint_from_training(ts, "v8")
            print(f"  OK   {ts.name}")
        except AssertionError as e:
            print(f"  FAIL {ts.name}: {e}")
